const { BaseMapGeneratorTest } = require('./base-map-generator-test');
const { FileOperations } = require('../lib/generator/file-operations');
const { GeneratedFoldersConstants } = require('../lib/constants');
const { FileHandler } = require('@reldens/server-utils');

class TestFileOperations extends BaseMapGeneratorTest
{

    async testExportsSingletonInstance()
    {
        await this.test('Exports singleton with expected method', async () => {
            this.assert(FileOperations, 'Expected FileOperations instance');
            this.assert(
                'function' === typeof FileOperations.cleanAutoGeneratedProcessMapFiles,
                'Expected cleanAutoGeneratedProcessMapFiles method'
            );
        });
    }

    async testCleanReturnsEarlyWhenDisabled()
    {
        await this.test('cleanAutoGeneratedProcessMapFiles returns early when disabled', async () => {
            let result = FileOperations.cleanAutoGeneratedProcessMapFiles(
                false,
                1,
                'full-path',
                'map-name',
                this.testDataFolder
            );
            this.assert(!result, 'Expected no action when flag disabled');
        });
    }

    async testCleanReturnsEarlyWhenNoOptimizedFolder()
    {
        await this.test('cleanAutoGeneratedProcessMapFiles returns early when optimized folder missing', async () => {
            let result = FileOperations.cleanAutoGeneratedProcessMapFiles(
                true,
                0,
                'full-path',
                'map-name',
                this.testDataFolder
            );
            this.assert(!result, 'Expected no action when optimized folder is missing');
        });
    }

    async testCleanRemovesOptimizedFilesAndEmptyFolder()
    {
        await this.test('cleanAutoGeneratedProcessMapFiles removes optimized files and the empty folder', async () => {
            let generatedFolder = FileHandler.joinPaths(this.testDataFolder, 'fileops-gen');
            if(!FileHandler.exists(generatedFolder)){
                FileHandler.createFolder(generatedFolder);
            }
            let optimizedFolder = FileHandler.joinPaths(generatedFolder, GeneratedFoldersConstants.OPTIMIZED_SUB_FOLDER);
            if(!FileHandler.exists(optimizedFolder)){
                FileHandler.createFolder(optimizedFolder);
            }
            let elementsFile = FileHandler.joinPaths(optimizedFolder, 'optimized-mymap-elements.json');
            let startsFile = FileHandler.joinPaths(optimizedFolder, 'optimized-elements-1.json');
            FileHandler.writeFile(elementsFile, '{}');
            FileHandler.writeFile(startsFile, '{}');
            FileOperations.cleanAutoGeneratedProcessMapFiles(true, 0, '', 'mymap', generatedFolder);
            this.assertEqual(FileHandler.exists(elementsFile), false);
            this.assertEqual(FileHandler.exists(startsFile), false);
            this.assertEqual(FileHandler.exists(optimizedFolder), false);
            if(FileHandler.exists(generatedFolder)){
                FileHandler.remove(generatedFolder);
            }
        });
    }

}

module.exports.TestFileOperations = TestFileOperations;
