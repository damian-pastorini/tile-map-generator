const { GeneratedFoldersConstants } = require('../constants');
const { FileHandler } = require('@reldens/server-utils');

class FileOperations
{

    cleanAutoGeneratedProcessMapFiles(
        removeOptimizedMapFilesAfterGeneration,
        factor,
        mapFileFullPath,
        mapName,
        generatedFolder
    ){
        if(!removeOptimizedMapFilesAfterGeneration){
            return;
        }
        let optimizedFolder = FileHandler.joinPaths(generatedFolder, GeneratedFoldersConstants.OPTIMIZED_SUB_FOLDER);
        if(!FileHandler.exists(optimizedFolder)){
            return;
        }
        let filePrefix = 'optimized-';
        let fileSuffix = '-elements';
        let fileStarts = 'optimized-elements-';
        let factorSuffix = '';
        if(factor){
            factorSuffix = '-x'+factor;
        }
        let fileExtensions = ['.png', '.json'];
        let mapFileName = FileHandler.getFileName(mapFileFullPath);
        for(let extension of fileExtensions){
            FileHandler.remove(FileHandler.joinPaths(optimizedFolder, filePrefix+mapName+fileSuffix+extension));
            FileHandler.remove(FileHandler.joinPaths(
                optimizedFolder,
                filePrefix+mapName+fileSuffix+factorSuffix+extension
            ));
            FileHandler.remove(FileHandler.joinPaths(optimizedFolder, filePrefix+mapFileName+extension));
            FileHandler.remove(FileHandler.joinPaths(optimizedFolder, filePrefix+mapFileName+factorSuffix+extension));
        }
        let folderFiles = FileHandler.readFolder(optimizedFolder);
        for(let fileName of folderFiles){
            let isElementsIntermediate = 0 === fileName.indexOf(filePrefix) && -1 !== fileName.indexOf(fileSuffix);
            if(0 === fileName.indexOf(fileStarts) || isElementsIntermediate){
                FileHandler.remove(FileHandler.joinPaths(optimizedFolder, fileName));
            }
        }
        if(0 === FileHandler.readFolder(optimizedFolder).length){
            FileHandler.remove(optimizedFolder);
        }
    }

}

module.exports.FileOperations = new FileOperations();
