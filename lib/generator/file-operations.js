const { FileHandler } = require('@reldens/server-utils');

class FileOperations
{

    cleanAutoGeneratedProcessMapFiles(
        removeOptimizedMapFilesAfterGeneration,
        factor,
        mapFileFullPath,
        mapName,
        generatedFolder
    ){
        if(!removeOptimizedMapFilesAfterGeneration){
            return;
        }
        let filePrefix = 'optimized-';
        let fileSuffix = '-elements';
        let fileStarts = 'optimized-elements-';
        let factorSuffix = '';
        if(factor){
            factorSuffix = '-x'+factor;
        }
        let fileExtensions = ['.png', '.json'];
        for(let extension of fileExtensions){
            let mapPath1 = mapFileFullPath.toString().replace('.json', '');
            let optimizedElementsFile = mapPath1.replace(
                mapName,
                filePrefix+mapName+fileSuffix+extension
            );
            let mapPath2 = mapFileFullPath.toString().replace('.json', '');
            let optimizedElementsFileFactor = mapPath2.replace(
                mapName,
                filePrefix+mapName+fileSuffix+factorSuffix+extension
            );
            if(FileHandler.exists(optimizedElementsFile)){
                FileHandler.remove(optimizedElementsFile);
            }
            if(FileHandler.exists(optimizedElementsFileFactor)){
                FileHandler.remove(optimizedElementsFileFactor);
            }
        }
        let folderFiles = FileHandler.readFolder(generatedFolder);
        for(let fileName of folderFiles){
            if(0 === fileName.indexOf(fileStarts)){
                FileHandler.remove(FileHandler.joinPaths(generatedFolder, fileName));
            }
        }
    }

}

module.exports.FileOperations = new FileOperations();
